    def recalculate_etalons(self, dock_id=None):
        """
        Пересчитать эталоны по выбранному сейчас растру.

        Контуры, по которым эталоны построены, сохранены в профилях, поэтому
        перенос на другой снимок — это повторная выборка пикселей по тем же
        границам. Имена и подписи классов сохраняются, статистика заменяется.
        """
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Пересчёт эталонов", text)

        if not self.profiles:
            warn("Эталонов нет.")
            return
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Выберите растровый слой в списке вверху панели.")
            return

        target_crs = raster_layer.crs()
        plan, missing = [], []
        for name in self.profiles.names():
            profile = self.profiles.get(name)
            geom = self.etalon_geometry(profile, target_crs=target_crs)
            if geom is None or geom.isEmpty():
                missing.append(profile.title)
            else:
                plan.append((profile, geom))
        if not plan:
            warn("Ни у одного эталона не сохранён контур.\n"
                 "Такие эталоны переносить не на что — постройте их заново "
                 "по объектам на новом растре.")
            return

        old_raster = {(p.raster or {}).get("name") for p, _ in plan}
        question = (f"Пересчитать эталонов: {len(plan)} по растру "
                    f"«{raster_layer.name()}»?\n"
                    f"Сейчас они посчитаны по: {', '.join(sorted(n or '—' for n in old_raster))}.")
        if missing:
            question += f"\n\n⚠ Без сохранённого контура (пропустим): {', '.join(missing)}"
        reply = QMessageBox.question(
            self.iface.mainWindow(), "Пересчёт эталонов", question,
            QMessageBox.Yes | QMessageBox.No, QMessageBox.Yes)
        if reply != QMessageBox.Yes:
            return

        _, progress_update, progress_finish = self._make_progress("Пересчёт эталонов")
        done, failed = [], []
        try:
            for index, (profile, geom) in enumerate(plan):
                progress_update(profile.title, index / len(plan) * 100)
                try:
                    sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON)
                    if not sample:
                        sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                               mode=MODE_BBOX)
                except Exception as e:
                    failed.append(f"{profile.title}: {e}")
                    continue
                if not sample:
                    failed.append(f"{profile.title}: нет пикселей растра")
                    continue

                source = dict(profile.source or {})
                source["geometry_wkt"] = geom.asWkt()
                source["geometry_crs"] = target_crs.authid()
                source["recalculated_from"] = (profile.raster or {}).get("name")
                self.profiles.add(ClassProfile.from_sample(
                    sample, name=profile.name, label=profile.label,
                    raster={"layer_id": raster_layer.id(), "name": raster_layer.name(),
                            "crs": target_crs.authid()},
                    source=source), make_active=False)
                done.append(f"{profile.title}: {sample.n_pixels} пикс., "
                            f"{sample.n_bands} кан.")
        finally:
            progress_finish()

        self._update_typicality_ui()
        text = f"Пересчитано эталонов: {len(done)}\n" + "\n".join(f"  • {d}" for d in done)
        if failed:
            text += "\n\nНе получилось:\n" + "\n".join(f"  • {f}" for f in failed)
        if missing:
            text += "\n\nБез контура пропущены:\n" + "\n".join(f"  • {m}" for m in missing)
        QMessageBox.information(self.iface.mainWindow(), "Пересчёт эталонов", text)
        print(f"↻ Эталоны пересчитаны по «{raster_layer.name()}»: {len(done)}")
        return done

