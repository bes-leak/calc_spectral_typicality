    def _connect_project_signals(self):
        if self.project_signals_connected:
            return
        self.project.layersAdded.connect(self._on_project_layers_changed)
        self.project.layersRemoved.connect(self._on_project_layers_removed)
        self.project.readProject.connect(self._on_project_read)
        try:
            self.project.layerTreeRoot().visibilityChanged.connect(
                self._on_project_layers_changed)
        except (AttributeError, TypeError):
            pass
        self.project_signals_connected = True

    def _disconnect_project_signals(self):
        if not self.project_signals_connected:
            return
        for signal, slot in (
            (self.project.layersAdded, self._on_project_layers_changed),
            (self.project.layersRemoved, self._on_project_layers_removed),
            (self.project.readProject, self._on_project_read),
        ):
            try:
                signal.disconnect(slot)
            except (TypeError, RuntimeError):
                pass
        try:
            self.project.layerTreeRoot().visibilityChanged.disconnect(
                self._on_project_layers_changed)
        except (AttributeError, TypeError, RuntimeError):
            pass
        self.project_signals_connected = False

    def _on_project_layers_changed(self, *args):
        """The set or visibility of layers changed; refresh the raster lists."""
        self._refresh_raster_combos()

    def _on_project_read(self, *args):
        """Another project was opened; re-read its assessments and profiles."""
        self.store.reload()
        self.profiles.reload()
        self.rasterLayers.clear()
        self._refresh_raster_combos()
        self._update_typicality_ui()

    def _on_project_layers_removed(self, layer_ids):
        """Layers were removed from the project; drop them from the histogram cache."""
        for layer_id in layer_ids or []:
            self.rasterLayers.pop(layer_id, None)
        self._refresh_raster_combos()

    def _refresh_raster_combos(self):
        """Fill the raster combo boxes in every dock."""
        options = [(layer.name(), layer.id())
                   for layer in get_visible_raster_layers(self.project)]
        for dock_id, dockwidget in self.dockwidgets.items():
            try:
                current = dockwidget.set_raster_options(options)
            except RuntimeError:      # the widget is already gone
                continue
            self.dock_raster_ids[dock_id] = current

    def _get_dock_raster(self, dock_id):
        """The raster chosen in a dock. None when there are no visible rasters."""
        layer_id = self.dock_raster_ids.get(dock_id)
        layer = self.project.mapLayer(layer_id) if layer_id else None
        if layer is not None and layer.isValid():
            return layer

        # the choice is stale (layer removed or hidden); refill the list
        self._refresh_raster_combos()
        layer_id = self.dock_raster_ids.get(dock_id)
        layer = self.project.mapLayer(layer_id) if layer_id else None
        return layer if (layer is not None and layer.isValid()) else None

    def onClosePlugin(self):
        """Cleanup on dockwidget close."""
        self.pluginIsActive = False

    def _safe(self, step, target, *args):
        """
        Run one unload step without letting an exception escape.

        `target` is the NAME of a method of this class, or a callable. A name is
        resolved inside the try: if the method is missing (the class is left over
        from an intermediate version of the file, edited while QGIS was running),
        that should be a line in the log, not the death of the whole unload.
        """
        try:
            func = getattr(self, target) if isinstance(target, str) else target
            func(*args)
        except Exception as e:
            print(f"⚠️ unload [{step}]: {type(e).__name__}: {e}")

    def unload(self):
        """
        Full cleanup on plugin unload. NEVER raises.

        If unload() throws, QGIS neither unregisters the plugin nor re-imports
        its modules: every subsequent "Reload plugin" calls the same broken
        instance again, and the only way out is a restart. Hence both each step
        is wrapped (so one failure does not cancel the rest) and the method as a
        whole (in case the cleanup machinery itself breaks).
        """
        try:
            # Disconnect signals
            if getattr(self, 'layer_tree_view', None):
                self._safe('layer tracking', lambda: (
                    self.layer_tree_view.currentLayerChanged.disconnect(
                        self.on_layer_changed)))
                self.layer_tree_view = None

            # Close all figures and widgets
            for dock_id in list(getattr(self, 'dockwidgets', {}).keys()):
                self._safe(f'dock {dock_id}', 'on_dockwidget_closed', dock_id)

            # Drop the highlight rubber band from the canvas
            self._safe('rubber band', '_clear_rubber_band')
            self._safe('etalon band', '_clear_etalon_band')
            self._safe('project signals', '_disconnect_project_signals')
            self._safe('raster cache', lambda: self.rasterLayers.clear())

            # Remove actions - the menu string must match the one used when adding
            # them (self.menu), otherwise the entry is not removed.
            for action in getattr(self, 'actions', []):
                self._safe('menu entry',
                           lambda a=action: self.iface.removePluginVectorMenu(self.menu, a))
                self._safe('toolbar icon',
                           lambda a=action: self.iface.removeToolBarIcon(a))
            self.actions = []

            if hasattr(self, 'toolbar'):
                del self.toolbar
        except Exception as e:
            print(f"unload: unexpected error: {type(e).__name__}: {e}")

    def run(self):
        """Main entry point."""
        if not self.dockwidgets:
            # First run — create initial dockwidget
            self.create_new_dockwidget(title_suffix="#1")
        else:
            # Ask user if they want a new window
            reply = QMessageBox.question(
                self.iface.mainWindow(),
                "Spectral Analysis",
                "Create a new analysis window?\n- Yes: add a second dock widget\n- No: show the existing ones",
                QMessageBox.Yes | QMessageBox.No,
                QMessageBox.No
            )
            if reply == QMessageBox.Yes:
                self.create_new_dockwidget(title_suffix="#2")
            else:
                for dw in self.dockwidgets.values():
                    dw.show()
                    dw.raise_()

