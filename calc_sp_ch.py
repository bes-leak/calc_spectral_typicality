    def _track_selection(self, layer):
        """Следить за выделением активного векторного слоя."""
        if self.selection_layer is not None:
            try:
                self.selection_layer.selectionChanged.disconnect(self._on_selection_changed)
            except (TypeError, RuntimeError):
                pass
            self.selection_layer = None
        if layer is not None and layer.type() == 0:
            try:
                layer.selectionChanged.connect(self._on_selection_changed)
                self.selection_layer = layer
            except (AttributeError, TypeError):
                pass

    def _on_selection_changed(self, *args):
        self._update_typicality_ui()

    def _selected_feature(self, vector_layer):
        """Единственный выделенный объект или None."""
        ids = vector_layer.selectedFeatureIds()
        if len(ids) != 1:
            return None
        request = QgsFeatureRequest().setFilterFid(ids[0])
        return next(vector_layer.getFeatures(request), None)

    def _etalon_text(self, class_field=None):
        """
        Сводка по библиотеке. Если задано поле класса, эталон при анализе
        берётся по нему, а не из списка — без этой строчки список выглядит
        неработающим.
        """
        text = self.profiles.summary()
        if class_field and self.profiles:
            text += f" · при анализе — по полю «{class_field}»"
        return text

    def _profile_for_feature(self, vector_layer, feature):
        """
        Эталон для объекта: по значению поля класса, иначе выбранный в списке.
        Returns (profile | None, пояснение выбора, класс объекта | None).
        """
        class_name = self.store.class_of(vector_layer.id(), feature)
        if class_name:
            profile = self.profiles.get(class_name)
            if profile is not None:
                return profile, f"по классу «{class_name}»", class_name
            # фраза подставляется после слова «эталон» — держим её согласованной
            return None, f"не найден для класса «{class_name}»", class_name
        return self.profiles.active, "выбран в списке", None

    def _update_typicality_ui(self, dock_id=None):
        """Обновить группу «Типичность» в одном или во всех доках."""
        dock_ids = [dock_id] if dock_id else list(self.dockwidgets.keys())
        if not dock_ids:
            return

        layer = self.iface.activeLayer()
        is_vector = layer is not None and layer.type() == 0

        if is_vector:
            # слой мог быть переоткрыт и получить новый id — подхватываем
            # прежние настройки и оценки по источнику
            adopted = self.store.adopt_layer(layer)
            if adopted:
                print(f"↻ Настройки слоя «{layer.name()}» перенесены с прежнего "
                      f"идентификатора ({adopted})")

        fields, id_field, class_field, value = [], "", "", None
        profile_for_object = None
        if is_vector:
            fields = [field.name() for field in layer.fields()]
            id_field = self.store.id_field(layer.id()) or ""
            class_field = self.store.class_field(layer.id()) or ""
            if not class_field:
                # слой раскрашен по классам — поле классификации уже выбрано
                # пользователем в стиле, незачем спрашивать второй раз
                suggested = categorized_class_field(layer)
                if suggested:
                    class_field = self.store.set_class_field(layer.id(), suggested)
                    print(f"↻ Поле класса взято из стиля слоя: «{suggested}»")
            selected_count = len(layer.selectedFeatureIds())
            feature = self._selected_feature(layer) if selected_count == 1 else None
            if feature is not None:
                key = self.store.key_for(layer.id(), feature)
                value = self.store.value(layer.id(), key)
                profile_for_object, reason, _ = self._profile_for_feature(layer, feature)
                suffix = f" · эталон {reason}" if class_field else ""
                info, enabled = f"Объект {key}: {label_for(value)}{suffix}", True
            elif selected_count:
                info, enabled = (f"Выделено объектов: {selected_count} — "
                                 "оценка ставится по одному"), False
            else:
                info, enabled = "Выделите один объект", False
        else:
            info, enabled = "Выберите векторный слой", False

        # автоопределение требует подходящего эталона для этого объекта
        auto_enabled = enabled and profile_for_object is not None

        for current in dock_ids:
            dockwidget = self.dockwidgets.get(current)
            if dockwidget is None:
                continue
            try:
                dockwidget.set_profile_options(self.profiles.options(),
                                               self.profiles.active_name)
                dockwidget.set_etalon_info(self._etalon_text(class_field))
                dockwidget.set_id_field_options(fields, id_field)
                dockwidget.set_class_field_options(fields, class_field)
                dockwidget.set_selection_info(info, enabled, auto_enabled,
                                              batch_enabled=is_vector and bool(self.profiles))
                dockwidget.set_typicality(value)
            except RuntimeError:      # виджет уже удалён
                continue

