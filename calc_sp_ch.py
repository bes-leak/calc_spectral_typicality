    def make_etalon(self, dock_id):
        """Build a class profile from the selected features."""
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Class profile", text)

        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Select a vector layer with features.")
            return
        features = vector_layer.selectedFeatures()
        if not features:
            warn("Select a feature (or several); the profile will be built from them.")
            return
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Select a raster layer in the list at the top of the panel.")
            return

        geom = self._get_union_geom_in_raster_crs(features, vector_layer, raster_layer)
        if geom is None or geom.isEmpty():
            warn("Could not obtain the feature geometry in the raster coordinate system.")
            return

        _, progress_update, progress_finish = self._make_progress("Class profile")
        try:
            sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON,
                                   progress=progress_update)
            if not sample:
                sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                       mode=MODE_BBOX, progress=progress_update)
        except Exception as e:
            progress_finish()
            warn(f"Could not read the pixels:\n{e}")
            return
        progress_finish()

        if not sample:
            warn("No raster data within the selected features.")
            return

        # the class name is taken from the class field of the selected features
        layer_id = vector_layer.id()
        class_values = {self.store.class_of(layer_id, f) for f in features}
        class_values.discard(None)
        mixed = len(class_values) > 1
        if len(class_values) == 1:
            default_name = next(iter(class_values))
        elif self.profiles.active_name:
            default_name = self.profiles.active_name
        else:
            default_name = vector_layer.name()

        # the legend label: nicer to show than a long raw value
        labels = category_labels(vector_layer)
        label = labels.get(default_name)

        prompt = "Class name:"
        if label:
            prompt = f"Class in the layer legend: \"{label}\".\nClass name:"
        if mixed:
            prompt = ("The selection spans several classes: "
                      + ", ".join(sorted(class_values))
                      + ".\nThere will be one profile. Class name:")
        name, accepted = QInputDialog.getText(
            self.iface.mainWindow(), "Class profile", prompt, text=default_name)
        if not accepted:
            return
        name = name.strip() or default_name
        if name != default_name:
            label = labels.get(name)          # the name changed, so look the label up again

        replacing = name in self.profiles
        if replacing:
            reply = QMessageBox.question(
                self.iface.mainWindow(), "Class profile",
                f"Profile \"{name}\" already exists. Replace it?",
                QMessageBox.Yes | QMessageBox.No, QMessageBox.Yes)
            if reply != QMessageBox.Yes:
                return

        profile = ClassProfile.from_sample(
            sample, name=name, label=label,
            raster={"layer_id": raster_layer.id(), "name": raster_layer.name(),
                    "crs": raster_layer.crs().authid()},
            source={"vector_layer": vector_layer.name(),
                    "feature_ids": [f.id() for f in features],
                    "class_field": self.store.class_field(layer_id),
                    "sampling_mode": MODE_POLYGON,
                    # geometry in the raster CRS: it is what highlights the profile on the
                    # map and recomputes it against another image, even if the feature
                    # identifiers have drifted in the meantime
                    "geometry_wkt": geom.asWkt(),
                    "geometry_crs": raster_layer.crs().authid()},
        )
        self.profiles.add(profile)
        self._update_typicality_ui()

        note = ("\nFew pixels relative to the number of bands: the covariance is heavily "
                "shrunk, so the Mahalanobis metrics will be unstable."
                if profile.singular or profile.shrinkage > 0.2 else "")
        QMessageBox.information(
            self.iface.mainWindow(), "Class profile",
            f"Profile \"{profile.title}\" {'updated' if replacing else 'built'}:\n"
            f"{profile.n_pixels} px, {profile.k} band(s), "
            f"features: {len(features)}\n"
            f"Class profiles in the library: {len(self.profiles)}{note}")
        print(f"★ Profile: {profile!r}")

