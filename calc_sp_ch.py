    def import_typicality(self, dock_id=None):
        """Load typicality assessments from a previously exported JSON."""
        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            QMessageBox.warning(self.iface.mainWindow(), "Assessments",
                                "Select the vector layer the assessments belong to.")
            return

        filepath, _ = QFileDialog.getOpenFileName(
            self.iface.mainWindow(), "Load typicality assessments", "",
            "Assessments (*.json *.csv)")
        if not filepath:
            return
        try:
            if filepath.lower().endswith(".csv"):
                info = load_typicality_csv(filepath)
            else:
                info = load_typicality(filepath)
        except (OSError, ValueError) as e:
            QMessageBox.critical(self.iface.mainWindow(), "Assessments",
                                 f"Could not read the file:\n{e}")
            return

        if not info["count"]:
            QMessageBox.information(
                self.iface.mainWindow(), "Assessments",
                "The file holds no assessments.\n\n"
                "Check that the export was made after the labelling: features must have "
                "their typicality field filled in.")
            return

        layer_id = vector_layer.id()
        current_field = self.store.id_field(layer_id) or ""
        # a CSV has no key field, so assume its keys match the current ones
        field_known = info.get("id_field_known", True)
        file_field = (info["id_field"] or "") if field_known else current_field

        # The main check: do the keys from the file match features of the layer?
        # Without it the import "succeeds", filing records under keys the layer does
        # not have, and nothing shows up in the panel.
        keys_by_field = {
            field: {feature_key(f, field or None) for f in vector_layer.getFeatures()}
            for field in {file_field, current_field}
        }
        file_keys = set(info["records"])
        matched = len(file_keys & keys_by_field.get(file_field, set()))

        if not matched:
            # the keys may fit another field, so point it out
            candidates = []
            for field in [""] + [f.name() for f in vector_layer.fields()]:
                keys = {feature_key(f, field or None) for f in vector_layer.getFeatures()}
                hits = len(file_keys & keys)
                if hits:
                    candidates.append((hits, field or "fid"))
            hint = ""
            if candidates:
                hits, field = max(candidates)
                hint = (f"\n\nThe keys appear to match the field \"{field}\" "
                        f"({hits} matches). Choose it as \"key:\" and try again.")
            QMessageBox.warning(
                self.iface.mainWindow(), "Assessments",
                f"None of the keys from the file matched a feature of layer "
                f"\"{vector_layer.name()}\".\n"
                f"In the file the keys come from \"{file_field or 'fid'}\", for example: "
                f"{', '.join(sorted(file_keys)[:3])}.{hint}")
            return

        warnings = []
        if info["vector_layer"] and info["vector_layer"] != vector_layer.name():
            warnings.append(f"the file was exported from layer \"{info['vector_layer']}\", "
                            f"while the active one is \"{vector_layer.name()}\"")
        if field_known and file_field != current_field:
            warnings.append(f"keys in the file come from \"{file_field or 'fid'}\", "
                            f"currently they come from \"{current_field or 'fid'}\", so the field will be replaced")
        if matched < info["count"]:
            warnings.append(f"features matched: {matched} of {info['count']}")

        question = f"Assessments to load: {info['count']}?"
        if warnings:
            question = "⚠ " + ";\n⚠ ".join(warnings) + f"\n\n{question}"
        reply = QMessageBox.question(
            self.iface.mainWindow(), "Assessments", question,
            QMessageBox.Yes | QMessageBox.No, QMessageBox.Yes)
        if reply != QMessageBox.Yes:
            return

        if field_known and file_field != current_field:
            self.store.set_id_field(layer_id, file_field or None)
        applied = self.store.import_records(layer_id, info["records"])
        self._update_typicality_ui()
        QMessageBox.information(
            self.iface.mainWindow(), "Assessments",
            f"Assessments loaded: {applied}, of which matched a feature: {matched}\n"
            f"Layer summary: {self.store.counts(layer_id)}")
        print(f"⬇ Assessments imported: {applied} (matched {matched})")


    def _clear_plot(self, dock_id, message=""):
        """Helper to clear plot with message."""
        self.dock_last_plot.pop(dock_id, None)
        if dock_id not in self.figures:
            return
        figure = self.figures[dock_id]
        canvas = self.canvases[dock_id]

        figure.clear()
        ax = figure.add_subplot(111)
        clear_axes_with_message(ax, message)
        canvas.draw()

    def _resolve_dock_id(self, dock_id=None):
        """Fallback to the first dockwidget; None if there is nothing to draw on."""
        if dock_id is None:
            if not self.dockwidgets:
                return None
            dock_id = next(iter(self.dockwidgets))
        return dock_id if dock_id in self.dockwidgets else None

    def _render_plot(self, dock_id, kind, histograms, title, xlabel, ylabel,
                     legend_fontsize=8):
        """Cache the computed histograms for this dock and draw them."""
        self.dock_last_plot[dock_id] = {
            'kind': kind,
            'histograms': histograms,
            'title': title,
            'xlabel': xlabel,
            'ylabel': ylabel,
            'legend_fontsize': legend_fontsize,
        }
        self._redraw(dock_id)

    def _redraw(self, dock_id):
        """Redraw the cached histograms with the dock's current plot type."""
        cache = self.dock_last_plot.get(dock_id)
        if not cache or dock_id not in self.figures:
            return
        figure = self.figures[dock_id]
        canvas = self.canvases[dock_id]

        figure.clear()
        ax = figure.add_subplot(111)
        plot_histograms(
            ax=ax,
            histograms=cache['histograms'],
            plot_type=self.dock_plot_types.get(dock_id, 'bar'),
            colors=self.colors,
            title=cache['title'],
            xlabel=cache['xlabel'],
            ylabel=cache['ylabel'],
            legend_fontsize=cache['legend_fontsize'],
        )
        figure.tight_layout()
        canvas.draw()

    def _cache_raster_layer(self, layer_id, layer):
        """Store overview histograms, evicting the oldest entry when full."""
        self.rasterLayers[layer_id] = layer
        while len(self.rasterLayers) > self.MAX_CACHED_LAYERS:
            self.rasterLayers.pop(next(iter(self.rasterLayers)))

    def plot_layers_distributions(self, dock_id=None):
        """Plot raster layer channel distributions for specific dockwidget."""
        dock_id = self._resolve_dock_id(dock_id)
        if dock_id is None:
            return

        current_layer = self.iface.layerTreeView().currentLayer()
        if not current_layer or current_layer.type() != 1:
            self._clear_plot(dock_id, "Select a raster layer")
            return

        current_layer_id = current_layer.id()

        # Cache of overview histograms. The raster is NOT loaded in full: a decimated
        # sample is read, and only counts/edges are kept.
        layer = self.rasterLayers.get(current_layer_id)
        if layer is None:
            _, progress_update, progress_finish = self._make_progress(
                f"Histogram of layer {current_layer.name()}")
            try:
                layer = RasterLayer.from_layer(current_layer, progress=progress_update)
            except Exception as e:
                progress_finish()
                QgsMessageLog.logMessage(f"Overview histogram failed: {e}",
                                         'SpectralCharacteristics', Qgis.Critical)
                self._clear_plot(dock_id, f"Could not read the raster:\n{e}")
                return
            progress_finish()

            if not layer:
                self._clear_plot(dock_id, "The raster holds no data to build a histogram from")
                return
            self._cache_raster_layer(current_layer_id, layer)

        histograms = []
        for channel_name, hist in layer.histogram().items():
            counts, bins = hist[0], hist[1]
            histograms.append((channel_name, counts, bins))

        self._render_plot(
            dock_id,
            kind='raster',
            histograms=histograms,
            title=f"Spectrum: {current_layer.name()}",
            xlabel="Pixel value",
            ylabel="Frequency",
            legend_fontsize=8,
        )

    def _get_union_geom_in_raster_crs(self, features, vector_layer, raster_layer):
        """
        Union geometries of all features and reproject to raster CRS.
        Returns QgsGeometry or None on failure.

        Important: a reprojection failure returns None. Carrying on with the
        original geometry would silently sample a different place on the map.
        """
        pairs = self._geoms_in_raster_crs(features, vector_layer, raster_layer)
        if pairs is None:
            return None
        return union_geometry([geom for _, geom in pairs])

    def _geoms_in_raster_crs(self, features, vector_layer, raster_layer):
        """[(feature, geom in the raster CRS)], or None if reprojection fails."""
        try:
            return geometries_in_crs(features, vector_layer.crs(), raster_layer.crs(),
                                     self.project)
        except CrsTransformError as e:
            QgsMessageLog.logMessage(f"Could not reproject the geometry: {e}",
                                     'SpectralCharacteristics', Qgis.Critical)
            print(f"⚠️ CRS transform failed: {e}")
            return None

    def _make_progress(self, title: str):
        """
        Creates a message-bar progress widget.
        Returns (item, update_fn, finish_fn).
        """


        msg_bar = self.iface.messageBar()

        progress_bar = QProgressBar()
        progress_bar.setMaximum(100)
        progress_bar.setValue(0)
        progress_bar.setAlignment(Qt.AlignLeft | Qt.AlignVCenter)
        progress_bar.setFixedWidth(150)

        item = msg_bar.createMessage(title)
        item.layout().addWidget(progress_bar)
        msg_bar.pushWidget(item, Qgis.Info)

        def update(message: str, pct=None):
            item.setText(f"{title}: {message}")
            if pct is not None:
                progress_bar.setValue(int(pct))
            QApplication.processEvents()

        def finish():
            msg_bar.popWidget(item)

        return item, update, finish

