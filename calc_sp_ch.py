    def auto_typicality(self, dock_id=None):
        """Automatic typicality assessment of the selected feature against a profile."""
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Automatic assessment", text)

        if not self.profiles:
            warn("There are no class profiles. Select the features of a class and press ★, or "
                 "load a profile from a file.")
            return

        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Select a vector layer with features.")
            return
        feature = self._selected_feature(vector_layer)
        if feature is None:
            warn("Select exactly one feature; assessments are made one at a time.")
            return

        profile, reason, class_name = self._profile_for_feature(vector_layer, feature)
        if profile is None:
            warn(f"The profile {reason}.\n\n"
                 f"Build a profile for this class (select its features and press ★), "
                 f"or clear the class field to compare against the one picked in the list.")
            return

        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Select a raster layer in the list at the top of the panel.")
            return

        pairs = self._geoms_in_raster_crs([feature], vector_layer, raster_layer)
        if not pairs:
            warn("Could not obtain the feature geometry in the raster coordinate system.")
            return
        geom = pairs[0][1]

        _, progress_update, progress_finish = self._make_progress("Automatic assessment")
        try:
            sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON,
                                   progress=progress_update)
            if not sample:
                sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                       mode=MODE_BBOX, progress=progress_update)
        except Exception as e:
            progress_finish()
            warn(f"Could not read the feature's pixels:\n{e}")
            return
        progress_finish()

        if not sample:
            warn("No raster data within the feature.")
            return

        key = self.store.key_for(vector_layer.id(), feature)
        label = f"{key} · {reason}" if class_name else str(key)
        try:
            dialog = AutoTypicalityDialog(
                profile, sample,
                parent=self.iface.mainWindow(),
                weights=self.auto_settings.get("weights"),
                thresholds=self.auto_settings.get("thresholds"),
                mode=self.auto_settings.get("mode", MODE_SUM),
                object_label=label,
            )
        except ValueError as e:          # the profile does not fit the raster
            warn(str(e))
            return

        if dialog.exec_() != dialog.Accepted:
            return

        result = dialog.result
        self.auto_settings = dialog.settings()
        self._save_auto_settings()
        if result is None or result.value is None:
            warn("No assessment computed; enable at least one metric.")
            return

        details = result.to_dict()
        details["raster_layer"] = raster_layer.name()
        details["class_profile"] = profile.name
        details["profile_choice"] = reason
        if class_name:
            details["object_class"] = class_name
        details["n_pixels"] = sample.n_pixels
        self.store.set(vector_layer.id(), key, result.value, source=AUTO, details=details)
        self._update_typicality_ui()
        print(f"⚙ {key}: score {result.score:.3f} → {result.value} "
              f"({label_for(result.value)})")

    def batch_typicality(self, dock_id=None):
        """Batch assessment: every feature against the profile of its own class."""
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Batch assessment", text)

        # processEvents() is called inside the loop, so the user has time to press
        # the button again; without the flag that gives a nested run, which corrupts
        # the store and brings QGIS down.
        if getattr(self, '_batch_running', False):
            return
        self._batch_running = True
        try:
            return self._batch_typicality(dock_id, warn)
        finally:
            self._batch_running = False

    def _batch_typicality(self, dock_id, warn):
        if not self.profiles:
            warn("There are no class profiles. Build at least one (★) or load one from a file.")
            return
        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Select a vector layer with features.")
            return
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Select a raster layer in the list at the top of the panel.")
            return

        features, selection = self.collect_export_features(vector_layer)
        if not features:
            warn("The layer has no features.")
            return

        layer_id = vector_layer.id()
        pairs = self._geoms_in_raster_crs(features, vector_layer, raster_layer)
        if not pairs:
            warn("Could not obtain the feature geometry in the raster coordinate system.")
            return

        # what and how much will be processed, shown BEFORE the run starts
        geoms = {feature.id(): geom for feature, geom in pairs}
        items, class_counts, manual = [], {}, 0
        for feature, _ in pairs:
            key = self.store.key_for(layer_id, feature)
            class_name = self.store.class_of(layer_id, feature)
            items.append((feature, key, class_name))
            class_counts[class_name] = class_counts.get(class_name, 0) + 1
            record = self.store.get(layer_id, key)
            if record and record.get("source") == MANUAL:
                manual += 1

        class_stats = [(name, count, (name in self.profiles) if name
                        else self.profiles.active is not None)
                       for name, count in sorted(class_counts.items(),
                                                 key=lambda item: (item[0] is None,
                                                                   item[0] or ""))]
        scope_text = (f"Features selected: {len(items)}" if selection == "selected"
                      else f"The whole layer \"{vector_layer.name()}\": {len(items)} features")

        dialog = BatchRunDialog(class_stats, scope_text, self.auto_settings,
                                parent=self.iface.mainWindow(), has_manual=manual)
        if dialog.exec_() != dialog.Accepted:
            return
        overwrite_manual = dialog.overwrite_manual()
        want_csv = dialog.want_csv()

        # --- the run, with progress and the option to cancel ---
        progress_dialog = QProgressDialog("Assessing typicality...", "Cancel", 0,
                                          len(items), self.iface.mainWindow())
        progress_dialog.setWindowTitle("Batch assessment")
        progress_dialog.setWindowModality(Qt.WindowModal)
        progress_dialog.setMinimumDuration(0)
        progress_dialog.setValue(0)

        def on_progress(index, total, key):
            progress_dialog.setValue(index)
            if key:
                progress_dialog.setLabelText(f"Feature {index + 1} of {total}: {key}")
            QApplication.processEvents()

        def skip_key(key):
            if overwrite_manual:
                return None
            record = self.store.get(layer_id, key)
            return SKIP_MANUAL if record and record.get("source") == MANUAL else None

        def sample_for(feature):
            geom = geoms.get(feature.id())
            if geom is None:
                return None
            sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON)
            if not sample:
                sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                       mode=MODE_BBOX)
            return sample

        try:
            report = run_batch(
                items,
                profile_for=lambda f: self._profile_for_feature(vector_layer, f),
                sample_for=sample_for,
                weights=self.auto_settings.get("weights"),
                thresholds=tuple(self.auto_settings.get("thresholds") or
                                 DEFAULT_THRESHOLDS),
                mode=self.auto_settings.get("mode", MODE_SUM),
                skip_key=skip_key,
                progress=on_progress,
                is_cancelled=progress_dialog.wasCanceled,
            )
        except Exception as e:
            progress_dialog.close()
            QgsMessageLog.logMessage(f"Batch failed: {e}", 'SpectralCharacteristics',
                                     Qgis.Critical)
            QMessageBox.critical(self.iface.mainWindow(), "Batch assessment",
                                 f"Error during the run:\n{e}")
            return
        progress_dialog.close()

        # flush=False plus a single flush at the end: otherwise every write serializes
        # the whole store into the project and the time grows quadratically
        for row in report.rows:
            self.store.set(layer_id, row["key"], row["value"], source=AUTO,
                           details=details_for_store(row, raster_layer.name()),
                           flush=False)
        self.store.flush()
        self._update_typicality_ui()

        saved = ""
        if want_csv and report.rows:
            filepath, _ = QFileDialog.getSaveFileName(
                self.iface.mainWindow(), "Save the results",
                f"{vector_layer.name()}_typicality.csv", "CSV (*.csv)")
            if filepath:
                try:
                    report.write_csv(filepath)
                    saved = f"\n\nCSV: {filepath}"
                except OSError as e:
                    saved = f"\n\nCSV not saved: {e}"

        QMessageBox.information(self.iface.mainWindow(), "Batch assessment",
                                report.summary_text() + saved)
        print(f"⚙ Batch: {report.processed} assessed, {len(report.skipped)} skipped")
        return report

    #: Default minimum feature size for the separability matrix
    SEPARABILITY_MIN_PIXELS = 10

    def separability_matrix(self, dock_id=None):
        """
        Run the features against every profile and export a separability matrix.
        Nothing is written to the store: this diagnoses the profiles, it does not
        label features.
        """
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Separability matrix", text)

        if getattr(self, '_batch_running', False):
            return
        self._batch_running = True
        try:
            return self._separability_matrix(dock_id, warn)
        finally:
            self._batch_running = False

    def _separability_matrix(self, dock_id, warn):
        if len(self.profiles) < 2:
            warn("At least two profiles are needed; the matrix shows how far the classes "
                 "can be told apart.")
            return
        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Select a vector layer with features.")
            return
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Select a raster layer in the list at the top of the panel.")
            return

        features, selection = self.collect_export_features(vector_layer)
        if not features:
            warn("The layer has no features.")
            return
        pairs = self._geoms_in_raster_crs(features, vector_layer, raster_layer)
        if not pairs:
            warn("Could not obtain the feature geometry in the raster coordinate system.")
            return

        layer_id = vector_layer.id()
        geoms = {feature.id(): geom for feature, geom in pairs}
        items = [(feature, self.store.key_for(layer_id, feature),
                  self.store.class_of(layer_id, feature)) for feature, _ in pairs]

        scope = ("selected" if selection == "selected" else "all")
        min_pixels, accepted = QInputDialog.getInt(
            self.iface.mainWindow(), "Separability matrix",
            f"Features ({scope}): {len(items)}, profiles: {len(self.profiles)}.\n"
            f"Every feature will be compared with every profile.\n\n"
            f"Small features blur the picture; skip features smaller than, in pixels:",
            self.SEPARABILITY_MIN_PIXELS, 1, 1000000)
        if not accepted:
            return

        progress_dialog = QProgressDialog("Comparing against every profile...", "Cancel",
                                          0, len(items), self.iface.mainWindow())
        progress_dialog.setWindowTitle("Separability matrix")
        progress_dialog.setWindowModality(Qt.WindowModal)
        progress_dialog.setMinimumDuration(0)
        progress_dialog.setValue(0)

        def on_progress(index, total, key):
            progress_dialog.setValue(index)
            if key:
                progress_dialog.setLabelText(f"Feature {index + 1} of {total}: {key}")
            QApplication.processEvents()

        def sample_for(feature):
            geom = geoms.get(feature.id())
            if geom is None:
                return None
            sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON)
            if not sample:
                sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                       mode=MODE_BBOX)
            return sample

        profiles = {name: self.profiles.get(name) for name in self.profiles.names()}
        try:
            report = run_separability(
                items, profiles, sample_for,
                weights=self.auto_settings.get("weights"),
                thresholds=tuple(self.auto_settings.get("thresholds") or
                                 DEFAULT_THRESHOLDS),
                mode=self.auto_settings.get("mode", MODE_SUM),
                min_pixels=min_pixels,
                progress=on_progress,
                is_cancelled=progress_dialog.wasCanceled,
            )
        except Exception as e:
            progress_dialog.close()
            QgsMessageLog.logMessage(f"Separability failed: {e}",
                                     'SpectralCharacteristics', Qgis.Critical)
            QMessageBox.critical(self.iface.mainWindow(), "Separability matrix",
                                 f"Error during the run:\n{e}")
            return
        progress_dialog.close()

        if not report.rows:
            warn("Not a single feature could be assessed.\n"
                 f"{report.summary_text()}")
            return

        filepath, _ = QFileDialog.getSaveFileName(
            self.iface.mainWindow(), "Save the separability matrix",
            f"{vector_layer.name()}_separability.csv", "CSV (*.csv)")
        saved = ""
        if filepath:
            try:
                report.write_csv(filepath)
                base = filepath[:-4] if filepath.lower().endswith(".csv") else filepath
                matrix_path = f"{base}_matrix.csv"
                report.write_matrix_csv(matrix_path)
                saved = (f"\n\nDetails: {filepath}"
                         f"\nMatrix: {matrix_path}")
            except OSError as e:
                saved = f"\n\nNot saved: {e}"

        QMessageBox.information(self.iface.mainWindow(), "Separability matrix",
                                report.summary_text() + saved)
        print(f"▦ Matrix: {report.processed} features x {len(report.names)} profiles")
        return report

