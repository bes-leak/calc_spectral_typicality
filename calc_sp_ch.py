    def on_dockwidget_closed(self, dock_id):
        """Cleanup when a specific dockwidget is closed."""
        # Remove mask overlay layer (if any)
        self._remove_mask_overlay(dock_id)

        # Close matplotlib figure to free memory
        if dock_id in self.figures:
            try:
                self.figures[dock_id].clear()
            except Exception:
                pass

        # Remove from dictionaries
        dockwidget = self.dockwidgets.pop(dock_id, None)
        for store in [self.figures, self.canvases, self.dock_plot_types,
                      self.dock_sampling_modes, self.dock_last_plot,
                      self.dock_raster_ids]:
            store.pop(dock_id, None)

        # Снять панель с главного окна и уничтожить её. Без этого closeEvent
        # только прячет док: он остаётся в QGIS с живыми сигналами и копится
        # при каждом повторном запуске / перезагрузке плагина.
        if dockwidget is not None:
            for signal in (dockwidget.closingPlugin, dockwidget.plotTypeChanged,
                           dockwidget.samplingModeChanged, dockwidget.rasterChanged,
                           dockwidget.analyzeClicked, dockwidget.exportJsonClicked,
                           dockwidget.typicalityChanged, dockwidget.idFieldChanged,
                           dockwidget.etalonRequested, dockwidget.etalonSaveRequested,
                           dockwidget.etalonLoadRequested,
                           dockwidget.etalonDeleteRequested,
                           dockwidget.etalonRecalcRequested,
                           dockwidget.profileSelected, dockwidget.classFieldChanged,
                           dockwidget.importTypicalityRequested,
                           dockwidget.autoTypicalityRequested,
                           dockwidget.batchTypicalityRequested,
                           dockwidget.separabilityRequested):
                try:
                    signal.disconnect()
                except TypeError:
                    pass
            try:
                self.iface.removeDockWidget(dockwidget)
            except Exception:
                pass
            dockwidget.setParent(None)
            dockwidget.deleteLater()

        # If last widget closed, disconnect layer tracking
        if not self.dockwidgets:
            self._track_selection(None)
            if self.layer_tree_view:
                try:
                    self.layer_tree_view.currentLayerChanged.disconnect(self.on_layer_changed)
                except (TypeError, RuntimeError):
                    pass
                self.layer_tree_view = None
            self._disconnect_project_signals()
            self.rasterLayers.clear()

        print(f"Closed and cleaned: {dock_id}")

    def on_raster_changed_in_dock(self, dock_id, layer_id):
        """User picked another raster for this dock."""
        if self.dock_raster_ids.get(dock_id) == layer_id:
            return
        self.dock_raster_ids[dock_id] = layer_id
        layer = self.project.mapLayer(layer_id)
        print(f"{dock_id}: Raster → {layer.name() if layer else layer_id}")

        # пересчитываем спектр объекта, если он был построен
        cache = self.dock_last_plot.get(dock_id)
        if cache and cache.get('kind') == 'feature':
            self.plot_vector_feature_spectrum(dock_id)

    def on_plot_type_changed_in_dock(self, dock_id, display_text):
        """Handle plot type change for specific dockwidget."""
        print(f"{dock_id}: Plot type → {display_text}")
        self.dock_plot_types[dock_id] = display_text

        # Перерисовываем уже посчитанные данные. Раньше здесь вызывались обе
        # функции подряд, и вторая затирала результат первой (для растрового
        # слоя график просто очищался сообщением «Выберите векторный слой»).
        if self.dock_last_plot.get(dock_id):
            self._redraw(dock_id)
            return

        layer = self.iface.activeLayer()
        if layer and layer.type() == 1:
            self.plot_layers_distributions(dock_id)
        elif layer and layer.type() == 0:
            self.plot_vector_feature_spectrum(dock_id)

    def on_sampling_mode_changed_in_dock(self, dock_id, sampling_mode: str):
        """Handle sampling mode change (bbox vs polygon) for specific dockwidget."""
        print(f"{dock_id}: Sampling mode → {sampling_mode}")
        self.dock_sampling_modes[dock_id] = sampling_mode
        self.plot_vector_feature_spectrum(dock_id)

    def on_layer_changed(self, layer):
        """React to active layer change — update ALL dockwidgets."""
        self._track_selection(layer)
        for dock_id in self.dockwidgets:
            if not layer:
                self._clear_plot(dock_id, "Выберите слой для анализа")
                continue
            if layer.type() == 1:  # Raster
                self.plot_layers_distributions(dock_id)
            elif layer.type() == 0:  # Vector
                self._clear_plot(dock_id,
                                 f"Векторный слой: {layer.name()}\n"
                                 "Выделите объект\n"
                                 "Нажмите 'Analyze selected object'")
        self._update_typicality_ui()

