    def recalculate_etalons(self, dock_id=None):
        """
        Recompute the class profiles against the currently selected raster.

        The outlines a profile was built from are stored in the profile itself,
        so moving to another image is simply re-sampling the pixels within the
        same boundaries. Class names and labels are kept, the statistics replaced.
        """
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Recomputing class profiles", text)

        if not self.profiles:
            warn("There are no class profiles.")
            return
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Select a raster layer in the list at the top of the panel.")
            return

        target_crs = raster_layer.crs()
        plan, missing = [], []
        for name in self.profiles.names():
            profile = self.profiles.get(name)
            geom = self.etalon_geometry(profile, target_crs=target_crs)
            if geom is None or geom.isEmpty():
                missing.append(profile.title)
            else:
                plan.append((profile, geom))
        if not plan:
            warn("Not one profile has a stored outline.\n"
                 "There is nothing to transfer such profiles onto; rebuild them "
                 "from the features on the new raster.")
            return

        old_raster = {(p.raster or {}).get("name") for p, _ in plan}
        question = (f"Recompute this many profiles: {len(plan)} against raster "
                    f"\"{raster_layer.name()}\"?\n"
                    f"They are currently computed from: {', '.join(sorted(n or '—' for n in old_raster))}.")
        if missing:
            question += f"\n\nWithout a stored outline (will be skipped): {', '.join(missing)}"
        reply = QMessageBox.question(
            self.iface.mainWindow(), "Recomputing class profiles", question,
            QMessageBox.Yes | QMessageBox.No, QMessageBox.Yes)
        if reply != QMessageBox.Yes:
            return

        _, progress_update, progress_finish = self._make_progress("Recomputing class profiles")
        done, failed = [], []
        try:
            for index, (profile, geom) in enumerate(plan):
                progress_update(profile.title, index / len(plan) * 100)
                try:
                    sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON)
                    if not sample:
                        sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                               mode=MODE_BBOX)
                except Exception as e:
                    failed.append(f"{profile.title}: {e}")
                    continue
                if not sample:
                    failed.append(f"{profile.title}: no raster pixels")
                    continue

                source = dict(profile.source or {})
                source["geometry_wkt"] = geom.asWkt()
                source["geometry_crs"] = target_crs.authid()
                source["recalculated_from"] = (profile.raster or {}).get("name")
                self.profiles.add(ClassProfile.from_sample(
                    sample, name=profile.name, label=profile.label,
                    raster={"layer_id": raster_layer.id(), "name": raster_layer.name(),
                            "crs": target_crs.authid()},
                    source=source), make_active=False)
                done.append(f"{profile.title}: {sample.n_pixels} px, "
                            f"{sample.n_bands} bands")
        finally:
            progress_finish()

        self._update_typicality_ui()
        text = f"Profiles recomputed: {len(done)}\n" + "\n".join(f"  • {d}" for d in done)
        if failed:
            text += "\n\nFailed:\n" + "\n".join(f"  • {f}" for f in failed)
        if missing:
            text += "\n\nSkipped for want of an outline:\n" + "\n".join(f"  • {m}" for m in missing)
        QMessageBox.information(self.iface.mainWindow(), "Recomputing class profiles", text)
        print(f"Profiles recomputed against \"{raster_layer.name()}\": {len(done)}")
        return done

