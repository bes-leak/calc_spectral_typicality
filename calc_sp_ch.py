    def make_etalon(self, dock_id):
        """Построить эталон класса по выделенным объектам."""
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Эталон", text)

        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Выберите векторный слой с объектами.")
            return
        features = vector_layer.selectedFeatures()
        if not features:
            warn("Выделите объект (или несколько) — по ним будет построен эталон.")
            return
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Выберите растровый слой в списке вверху панели.")
            return

        geom = self._get_union_geom_in_raster_crs(features, vector_layer, raster_layer)
        if geom is None or geom.isEmpty():
            warn("Не удалось получить геометрию объектов в системе координат растра.")
            return

        _, progress_update, progress_finish = self._make_progress("Эталон класса")
        try:
            sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON,
                                   progress=progress_update)
            if not sample:
                sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                       mode=MODE_BBOX, progress=progress_update)
        except Exception as e:
            progress_finish()
            warn(f"Не удалось прочитать пиксели:\n{e}")
            return
        progress_finish()

        if not sample:
            warn("Нет данных растра в пределах выделенных объектов.")
            return

        # имя класса подставляем из поля класса выделенных объектов
        layer_id = vector_layer.id()
        class_values = {self.store.class_of(layer_id, f) for f in features}
        class_values.discard(None)
        mixed = len(class_values) > 1
        if len(class_values) == 1:
            default_name = next(iter(class_values))
        elif self.profiles.active_name:
            default_name = self.profiles.active_name
        else:
            default_name = vector_layer.name()

        # подпись из легенды слоя: показывать её удобнее, чем длинное значение
        labels = category_labels(vector_layer)
        label = labels.get(default_name)

        prompt = "Название класса:"
        if label:
            prompt = f"Класс в легенде слоя: «{label}».\nНазвание класса:"
        if mixed:
            prompt = ("В выделении несколько классов: "
                      + ", ".join(sorted(class_values))
                      + ".\nЭталон будет один. Название класса:")
        name, accepted = QInputDialog.getText(
            self.iface.mainWindow(), "Эталон класса", prompt, text=default_name)
        if not accepted:
            return
        name = name.strip() or default_name
        if name != default_name:
            label = labels.get(name)          # имя поменяли — подпись ищем заново

        replacing = name in self.profiles
        if replacing:
            reply = QMessageBox.question(
                self.iface.mainWindow(), "Эталон класса",
                f"Эталон «{name}» уже есть. Заменить его?",
                QMessageBox.Yes | QMessageBox.No, QMessageBox.Yes)
            if reply != QMessageBox.Yes:
                return

        profile = ClassProfile.from_sample(
            sample, name=name, label=label,
            raster={"layer_id": raster_layer.id(), "name": raster_layer.name(),
                    "crs": raster_layer.crs().authid()},
            source={"vector_layer": vector_layer.name(),
                    "feature_ids": [f.id() for f in features],
                    "class_field": self.store.class_field(layer_id),
                    "sampling_mode": MODE_POLYGON,
                    # геометрия в CRS растра: по ней эталон подсвечивается на
                    # карте и пересчитывается по другому снимку, даже если
                    # идентификаторы объектов успели поехать
                    "geometry_wkt": geom.asWkt(),
                    "geometry_crs": raster_layer.crs().authid()},
        )
        self.profiles.add(profile)
        self._update_typicality_ui()

        note = ("\n⚠ Пикселей мало относительно числа каналов: ковариация сильно "
                "сжата, метрики Махаланобиса будут неустойчивы."
                if profile.singular or profile.shrinkage > 0.2 else "")
        QMessageBox.information(
            self.iface.mainWindow(), "Эталон",
            f"Эталон «{profile.title}» {'обновлён' if replacing else 'построен'}:\n"
            f"{profile.n_pixels} пикс., {profile.k} канал(ов), "
            f"объектов: {len(features)}\n"
            f"Всего эталонов в библиотеке: {len(self.profiles)}{note}")
        print(f"★ Эталон: {profile!r}")

