    def auto_typicality(self, dock_id=None):
        """Автоопределение типичности выделенного объекта по эталону."""
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Автоопределение", text)

        if not self.profiles:
            warn("Эталонов нет. Выделите объекты класса и нажмите ★ либо "
                 "загрузите профиль из файла.")
            return

        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Выберите векторный слой с объектами.")
            return
        feature = self._selected_feature(vector_layer)
        if feature is None:
            warn("Выделите ровно один объект — оценка считается по одному.")
            return

        profile, reason, class_name = self._profile_for_feature(vector_layer, feature)
        if profile is None:
            warn(f"Эталон {reason}.\n\n"
                 f"Постройте эталон для этого класса (выделите его объекты и нажмите ★) "
                 f"или снимите поле класса, чтобы сравнивать с выбранным в списке.")
            return

        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Выберите растровый слой в списке вверху панели.")
            return

        pairs = self._geoms_in_raster_crs([feature], vector_layer, raster_layer)
        if not pairs:
            warn("Не удалось получить геометрию объекта в системе координат растра.")
            return
        geom = pairs[0][1]

        _, progress_update, progress_finish = self._make_progress("Автоопределение")
        try:
            sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON,
                                   progress=progress_update)
            if not sample:
                sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                       mode=MODE_BBOX, progress=progress_update)
        except Exception as e:
            progress_finish()
            warn(f"Не удалось прочитать пиксели объекта:\n{e}")
            return
        progress_finish()

        if not sample:
            warn("Нет данных растра в пределах объекта.")
            return

        key = self.store.key_for(vector_layer.id(), feature)
        label = f"{key} · {reason}" if class_name else str(key)
        try:
            dialog = AutoTypicalityDialog(
                profile, sample,
                parent=self.iface.mainWindow(),
                weights=self.auto_settings.get("weights"),
                thresholds=self.auto_settings.get("thresholds"),
                mode=self.auto_settings.get("mode", MODE_SUM),
                object_label=label,
            )
        except ValueError as e:          # эталон не подходит к растру
            warn(str(e))
            return

        if dialog.exec_() != dialog.Accepted:
            return

        result = dialog.result
        self.auto_settings = dialog.settings()
        self._save_auto_settings()
        if result is None or result.value is None:
            warn("Оценка не посчитана — включите хотя бы одну метрику.")
            return

        details = result.to_dict()
        details["raster_layer"] = raster_layer.name()
        details["class_profile"] = profile.name
        details["profile_choice"] = reason
        if class_name:
            details["object_class"] = class_name
        details["n_pixels"] = sample.n_pixels
        self.store.set(vector_layer.id(), key, result.value, source=AUTO, details=details)
        self._update_typicality_ui()
        print(f"⚙ {key}: score {result.score:.3f} → {result.value} "
              f"({label_for(result.value)})")

    def batch_typicality(self, dock_id=None):
        """Пакетная оценка: каждый объект против эталона своего класса."""
        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Пакетная оценка", text)

        # Внутри цикла зовётся processEvents(), поэтому пользователь успевает
        # нажать кнопку повторно — без флага получается вложенный прогон,
        # который портит хранилище и роняет QGIS.
        if getattr(self, '_batch_running', False):
            return
        self._batch_running = True
        try:
            return self._batch_typicality(dock_id, warn)
        finally:
            self._batch_running = False

    def _batch_typicality(self, dock_id, warn):
        if not self.profiles:
            warn("Эталонов нет. Постройте хотя бы один (★) или загрузите из файла.")
            return
        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Выберите векторный слой с объектами.")
            return
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Выберите растровый слой в списке вверху панели.")
            return

        features, selection = self.collect_export_features(vector_layer)
        if not features:
            warn("В слое нет объектов.")
            return

        layer_id = vector_layer.id()
        pairs = self._geoms_in_raster_crs(features, vector_layer, raster_layer)
        if not pairs:
            warn("Не удалось получить геометрию объектов в системе координат растра.")
            return

        # что и сколько будет обработано — показываем ДО запуска
        geoms = {feature.id(): geom for feature, geom in pairs}
        items, class_counts, manual = [], {}, 0
        for feature, _ in pairs:
            key = self.store.key_for(layer_id, feature)
            class_name = self.store.class_of(layer_id, feature)
            items.append((feature, key, class_name))
            class_counts[class_name] = class_counts.get(class_name, 0) + 1
            record = self.store.get(layer_id, key)
            if record and record.get("source") == MANUAL:
                manual += 1

        class_stats = [(name, count, (name in self.profiles) if name
                        else self.profiles.active is not None)
                       for name, count in sorted(class_counts.items(),
                                                 key=lambda item: (item[0] is None,
                                                                   item[0] or ""))]
        scope_text = (f"Выделено объектов: {len(items)}" if selection == "selected"
                      else f"Весь слой «{vector_layer.name()}»: {len(items)} объектов")

        dialog = BatchRunDialog(class_stats, scope_text, self.auto_settings,
                                parent=self.iface.mainWindow(), has_manual=manual)
        if dialog.exec_() != dialog.Accepted:
            return
        overwrite_manual = dialog.overwrite_manual()
        want_csv = dialog.want_csv()

        # --- прогон с прогрессом и возможностью прервать ---
        progress_dialog = QProgressDialog("Оценка типичности…", "Прервать", 0,
                                          len(items), self.iface.mainWindow())
        progress_dialog.setWindowTitle("Пакетная оценка")
        progress_dialog.setWindowModality(Qt.WindowModal)
        progress_dialog.setMinimumDuration(0)
        progress_dialog.setValue(0)

        def on_progress(index, total, key):
            progress_dialog.setValue(index)
            if key:
                progress_dialog.setLabelText(f"Объект {index + 1} из {total}: {key}")
            QApplication.processEvents()

        def skip_key(key):
            if overwrite_manual:
                return None
            record = self.store.get(layer_id, key)
            return SKIP_MANUAL if record and record.get("source") == MANUAL else None

        def sample_for(feature):
            geom = geoms.get(feature.id())
            if geom is None:
                return None
            sample = sample_raster(raster_layer, geom=geom, mode=MODE_POLYGON)
            if not sample:
                sample = sample_raster(raster_layer, rect=geom.boundingBox(),
                                       mode=MODE_BBOX)
            return sample

        try:
            report = run_batch(
                items,
                profile_for=lambda f: self._profile_for_feature(vector_layer, f),
                sample_for=sample_for,
                weights=self.auto_settings.get("weights"),
                thresholds=tuple(self.auto_settings.get("thresholds") or
                                 DEFAULT_THRESHOLDS),
                mode=self.auto_settings.get("mode", MODE_SUM),
                skip_key=skip_key,
                progress=on_progress,
                is_cancelled=progress_dialog.wasCanceled,
            )
        except Exception as e:
            progress_dialog.close()
            QgsMessageLog.logMessage(f"Batch failed: {e}", 'SpectralCharacteristics',
                                     Qgis.Critical)
            QMessageBox.critical(self.iface.mainWindow(), "Пакетная оценка",
                                 f"Ошибка при прогоне:\n{e}")
            return
        progress_dialog.close()

        # flush=False + один flush в конце: иначе каждая запись сериализует всё
        # хранилище в проект, и время растёт квадратично по числу объектов
        for row in report.rows:
            self.store.set(layer_id, row["key"], row["value"], source=AUTO,
                           details=details_for_store(row, raster_layer.name()),
                           flush=False)
        self.store.flush()
        self._update_typicality_ui()

        saved = ""
        if want_csv and report.rows:
            filepath, _ = QFileDialog.getSaveFileName(
                self.iface.mainWindow(), "Сохранить результаты",
                f"{vector_layer.name()}_typicality.csv", "CSV (*.csv)")
            if filepath:
                try:
                    report.write_csv(filepath)
                    saved = f"\n\nCSV: {filepath}"
                except OSError as e:
                    saved = f"\n\n⚠ CSV не сохранён: {e}"

        QMessageBox.information(self.iface.mainWindow(), "Пакетная оценка",
                                report.summary_text() + saved)
        print(f"⚙ Пакет: {report.processed} оценено, {len(report.skipped)} пропущено")
        return report

