    def etalon_geometry(self, profile, target_crs=None):
        """
        Геометрия, по которой построен эталон, в нужной CRS.

        Берём сохранённый контур; если его нет (профиль из ранней версии) —
        собираем по id объектов активного слоя, но это менее надёжно:
        идентификаторы могли поехать при пересохранении слоя.
        """
        if profile is None:
            return None
        source = profile.source or {}
        geom, src_crs = None, None

        wkt = source.get("geometry_wkt")
        if wkt:
            candidate = QgsGeometry.fromWkt(wkt)
            if candidate is not None and not candidate.isEmpty():
                geom = candidate
                src_crs = QgsCoordinateReferenceSystem(
                    source.get("geometry_crs")
                    or (profile.raster or {}).get("crs") or "")

        if geom is None:
            layer = self.iface.activeLayer()
            ids = source.get("feature_ids") or []
            if not layer or layer.type() != 0 or not ids:
                return None
            request = QgsFeatureRequest().setFilterFids(list(ids))
            geoms = [QgsGeometry(f.geometry()) for f in layer.getFeatures(request)
                     if f.geometry() and not f.geometry().isEmpty()]
            geom = union_geometry(geoms)
            src_crs = layer.crs()

        if geom is None or target_crs is None or src_crs is None or not src_crs.isValid():
            return geom
        return geometry_in_crs(geom, src_crs, target_crs, self.project)

    def _clear_etalon_band(self):
        band, self.etalon_band = getattr(self, 'etalon_band', None), None
        if band is None:
            return
        try:
            band.reset(QgsWkbTypes.PolygonGeometry)
            self.iface.mapCanvas().scene().removeItem(band)
        except Exception:
            pass

    def highlight_etalon(self, profile):
        """Показать на карте объекты, по которым построен выбранный эталон."""
        self._clear_etalon_band()
        canvas = self.iface.mapCanvas()
        geom = self.etalon_geometry(profile, target_crs=canvas.mapSettings().destinationCrs())
        if geom is None or geom.isEmpty():
            return False

        band = QgsRubberBand(canvas, QgsWkbTypes.PolygonGeometry)
        band.setColor(QColor(42, 120, 214))            # синий — отличается от
        band.setFillColor(QColor(42, 120, 214, 45))    # красной подсветки анализа
        band.setStrokeColor(QColor(42, 120, 214))
        band.setWidth(3)
        band.addGeometry(geom, None)
        self.etalon_band = band
        return True

