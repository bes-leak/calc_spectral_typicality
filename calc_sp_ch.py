    def _safe(self, step, target, *args):
        """
        Выполнить шаг выгрузки, не давая исключению вырваться наружу.

        `target` — ИМЯ метода этого класса либо вызываемый объект. Имя
        разрешается внутри try: если метода нет (класс остался от промежуточной
        версии файла, отредактированного при живом QGIS), это должно быть
        строчкой в логе, а не падением всей выгрузки.
        """
        try:
            func = getattr(self, target) if isinstance(target, str) else target
            func(*args)
        except Exception as e:
            print(f"⚠️ unload [{step}]: {type(e).__name__}: {e}")

    def unload(self):
        """
        Full cleanup on plugin unload. НИКОГДА не бросает исключений.

        Если unload() падает, QGIS не снимает плагин с регистрации и не
        перечитывает модули: каждый следующий «Reload plugin» снова зовёт тот
        же сломанный экземпляр, и выйти из этого можно только перезапуском.
        Поэтому обёрнут и каждый шаг (чтобы сбой одного не отменил остальные),
        и метод целиком (на случай поломки самого механизма уборки).
        """
        try:
            # Disconnect signals
            if getattr(self, 'layer_tree_view', None):
                self._safe('layer tracking', lambda: (
                    self.layer_tree_view.currentLayerChanged.disconnect(
                        self.on_layer_changed)))
                self.layer_tree_view = None

            # Close all figures and widgets
            for dock_id in list(getattr(self, 'dockwidgets', {}).keys()):
                self._safe(f'dock {dock_id}', 'on_dockwidget_closed', dock_id)

            # Drop the highlight rubber band from the canvas
            self._safe('rubber band', '_clear_rubber_band')
            self._safe('etalon band', '_clear_etalon_band')
            self._safe('project signals', '_disconnect_project_signals')
            self._safe('raster cache', lambda: self.rasterLayers.clear())

            # Remove actions — строка меню должна совпадать с той, что была
            # использована при добавлении (self.menu), иначе пункт не удалится.
            for action in getattr(self, 'actions', []):
                self._safe('menu entry',
                           lambda a=action: self.iface.removePluginVectorMenu(self.menu, a))
                self._safe('toolbar icon',
                           lambda a=action: self.iface.removeToolBarIcon(a))
            self.actions = []

            if hasattr(self, 'toolbar'):
                del self.toolbar
        except Exception as e:
            print(f"⚠️ unload: непредвиденная ошибка: {type(e).__name__}: {e}")

    def run(self):
        """Main entry point."""
        if not self.dockwidgets:
            # First run — create initial dockwidget
            self.create_new_dockwidget(title_suffix="#1")
        else:
            # Ask user if they want a new window
            reply = QMessageBox.question(
                self.iface.mainWindow(),
                "Spectral Analysis",
                "Создать новое окно анализа?\n• Да — добавить второй док-виджет\n• Нет — показать существующие",
                QMessageBox.Yes | QMessageBox.No,
                QMessageBox.No
            )
            if reply == QMessageBox.Yes:
                self.create_new_dockwidget(title_suffix="#2")
            else:
                for dw in self.dockwidgets.values():
                    dw.show()
                    dw.raise_()

