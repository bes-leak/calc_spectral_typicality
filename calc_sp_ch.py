    def export_feature_json(self, dock_id=None):
        """
        Export the feature spectral characteristics to JSON v2: one record per
        feature, with its attributes and typicality assessment.
        """
        dock_id = self._resolve_dock_id(dock_id)
        if dock_id is None:
            return

        def warn(text):
            QMessageBox.warning(self.iface.mainWindow(), "Export JSON", text)

        # --- active vector layer ---
        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            warn("Select a vector layer with features.")
            return

        # --- raster chosen in this dock ---
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            warn("Select a raster layer in the list at the top of the panel.\n"
                 "If the list is empty, add a visible raster layer.")
            return

        features, selection = self.collect_export_features(vector_layer)
        if not features:
            warn("The layer has no features to export.")
            return

        if selection == "all" and len(features) >= self.BULK_CONFIRM_THRESHOLD:
            reply = QMessageBox.question(
                self.iface.mainWindow(), "Export JSON",
                f"Nothing is selected, so the whole layer will be exported: {len(features)} features.\n"
                "This may take a while. Continue?",
                QMessageBox.Yes | QMessageBox.No, QMessageBox.No)
            if reply != QMessageBox.Yes:
                return

        # --- the geometry of every feature, in the raster CRS ---
        pairs = self._geoms_in_raster_crs(features, vector_layer, raster_layer)
        if pairs is None:
            warn("Could not reproject the feature geometry "
                 "into the raster coordinate system (see the message log).")
            return
        if not pairs:
            warn("The features have no geometry.")
            return

        layer_id = vector_layer.id()
        keys = [self.store.key_for(layer_id, feature) for feature, _ in pairs]

        # --- pick save path ---
        suffix = "selected" if selection == "selected" else "all"
        default_name = f"{vector_layer.name()}_{suffix}_{len(pairs)}obj_spectral.json"
        filepath, _ = QFileDialog.getSaveFileName(
            self.iface.mainWindow(),
            "Save spectral JSON",
            default_name,
            "JSON (*.json)",
        )
        if not filepath:
            return  # user cancelled

        # --- export with progress bar ---
        _, progress_update, progress_finish = self._make_progress("Exporting JSON")
        try:
            export_features_json(
                filepath,
                vector_layer=vector_layer,
                raster_layer=raster_layer,
                feature_geoms=pairs,
                keys=keys,
                typicality=self.store.for_layer(layer_id),
                class_profile=self.profiles.active,
                class_profiles={name: self.profiles.get(name)
                                for name in self.profiles.names()},
                id_field=self.store.id_field(layer_id),
                class_field=self.store.class_field(layer_id),
                selection=selection,
                progress=progress_update,
            )
            progress_finish()
            QMessageBox.information(
                self.iface.mainWindow(),
                "Export JSON",
                f"Features saved: {len(pairs)}\n{filepath}",
            )
            print(f"✅ JSON exported ({len(pairs)} objects): {filepath}")
        except Exception as e:
            progress_finish()
            QgsMessageLog.logMessage(f"JSON export failed: {e}",
                                     'SpectralCharacteristics', Qgis.Critical)
            QMessageBox.critical(
                self.iface.mainWindow(),
                "Export JSON",
                f"Error during export:\n{e}",
            )
            print(f"❌ JSON export error: {e}")

    def plot_vector_feature_spectrum(self, dock_id=None):
        """Plot spectral distribution for all selected vector features."""
        dock_id = self._resolve_dock_id(dock_id)
        if dock_id is None:
            return

        # --- active vector layer ---
        vector_layer = self.iface.activeLayer()
        if not vector_layer or vector_layer.type() != 0:
            self._clear_plot(dock_id, "Select a vector layer")
            return

        # --- selected features ---
        # No "let us take the first feature of the layer": exactly what is selected
        # gets analysed, otherwise a random feature ends up on the plot.
        selected_features = vector_layer.selectedFeatures()
        if not selected_features:
            self._clear_plot(dock_id,
                             f"Layer: {vector_layer.name()}\n"
                             "Select a feature on the map\n"
                             "and press 'Analyse'")
            return

        # --- raster chosen in this dock ---
        raster_layer = self._get_dock_raster(dock_id)
        if raster_layer is None:
            self._clear_plot(dock_id, "Select a raster layer in the list at the top of the panel\n"
                                      "(there are no visible raster layers)")
            return

        # --- union all selected geometries + reproject to raster CRS ---
        # From here on ALL geometry (bbox included) lives in the raster CRS.
        geom = self._get_union_geom_in_raster_crs(selected_features, vector_layer, raster_layer)
        if not geom or geom.isEmpty():
            self._clear_plot(dock_id, "Could not obtain the feature geometry\n"
                                      "in the raster coordinate system")
            return

        # --- sample raster values ---
        sampling_mode = self.dock_sampling_modes.get(dock_id, MODE_POLYGON)
        _, progress_update, progress_finish = self._make_progress("Spectral analysis")

        try:
            if sampling_mode == MODE_BBOX:
                # the mask overlay only applies to polygon mode
                self._remove_mask_overlay(dock_id)
                sample = sample_raster(
                    raster_layer, rect=geom.boundingBox(), mode=MODE_BBOX,
                    progress=progress_update,
                )
            else:
                # polygon mode: strictly inside polygon via vectorized ray casting
                sample = sample_raster(
                    raster_layer, geom=geom, mode=MODE_POLYGON,
                    progress=progress_update,
                )
                if not sample:
                    # fallback to bbox for non-polygon geometries or empty mask
                    sample = sample_raster(
                        raster_layer, rect=geom.boundingBox(), mode=MODE_BBOX,
                        progress=progress_update,
                    )
                self._show_polygon_mask_overlay(dock_id, raster_layer, geom)
        except ValueError as e:
            # the sampling window is too large, and the like
            progress_finish()
            self._clear_plot(dock_id, str(e))
            return
        except Exception as e:
            progress_finish()
            QgsMessageLog.logMessage(f"Sampling failed: {e}", 'SpectralCharacteristics', Qgis.Critical)
            self._clear_plot(dock_id, f"Error while sampling pixels:\n{e}")
            return

        progress_finish()

        if not sample:
            self._clear_plot(dock_id, "No raster data within the feature")
            return

        # --- highlight the actual sampled window on map ---
        self.highlight_analysis_rect(sample.rect, raster_layer)

        # --- plot ---
        series = [(name, sample.values[:, i]) for i, name in enumerate(sample.band_names)]
        self._render_plot(
            dock_id,
            kind='feature',
            histograms=values_to_histograms(series, histogram),
            title=(f"Spectrum: {vector_layer.name()} | ID={get_feature_ids(selected_features)}\n"
                   f"{raster_layer.name()} · {sample.n_pixels} px - {sampling_mode}"),
            xlabel="Pixel value",
            ylabel="Frequency",
            legend_fontsize=7,
        )
        print(f"Spectrum built for features {get_feature_ids(selected_features)} "
              f"({sample.n_pixels} px x {sample.n_bands} band(s))")


    def _remove_mask_overlay(self, dock_id):
        """
        Drop the mask overlay layer belonging to this dock (if any) and delete
        its temporary GeoTIFF; otherwise every analysis run leaves a file in the
        temp folder forever.
        """
        old = self.dock_mask_layers.pop(dock_id, None)
        if not old:
            return
        try:
            source = old.source()
        except Exception:
            source = None
        try:
            self.project.removeMapLayer(old.id())
        except Exception:
            pass
        # the file is only released once the layer is removed
        remove_mask_file(source)

    def _show_polygon_mask_overlay(self, dock_id, raster_layer, geom):
        """Create/update raster mask overlay showing pixels used for polygon sampling."""
        self._remove_mask_overlay(dock_id)

        mask_layer = create_polygon_mask_raster(
            project=self.project,
            raster_layer=raster_layer,
            geom=geom,
            name=f"mask_{dock_id}",
        )
        if mask_layer:
            self.dock_mask_layers[dock_id] = mask_layer

    def _clear_rubber_band(self):
        """Remove the highlight rubber band from the map canvas."""
        band, self.rubber_band = self.rubber_band, None
        if band is None:
            return
        try:
            band.reset(QgsWkbTypes.PolygonGeometry)
            self.iface.mapCanvas().scene().removeItem(band)
        except Exception:
            pass

    def highlight_analysis_rect(self, rect, raster_layer, duration_ms=3000):
        """Temporarily highlight analysis rectangle on map canvas."""
        if rect is None:
            return
        # Remove previous rubber band
        self._clear_rubber_band()

        self.rubber_band = QgsRubberBand(self.iface.mapCanvas(), QgsWkbTypes.PolygonGeometry)
        self.rubber_band.setColor(QColor(255, 0, 0))
        self.rubber_band.setWidth(2)
        self.rubber_band.setFillColor(QColor(255, 0, 0, 50))
        self.rubber_band.setStrokeColor(QColor(255, 255, 0))
        self.rubber_band.setOpacity(0.5)

        rect_geometry = QgsGeometry.fromRect(rect)
        crs = raster_layer.crs() if hasattr(raster_layer, 'crs') else None
        self.rubber_band.addGeometry(rect_geometry, crs)

        # Auto-remove after timeout (only if this is still the same highlight)
        band = self.rubber_band
        QTimer.singleShot(
            duration_ms,
            lambda: self._clear_rubber_band() if self.rubber_band is band else None,
        )

