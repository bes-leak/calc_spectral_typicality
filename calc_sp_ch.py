    def add_action(self, icon_path, text, callback, enabled_flag=True,
                   add_to_menu=True, add_to_toolbar=True, status_tip=None,
                   whats_this=None, parent=None):
        """Add toolbar icon."""
        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)
        if status_tip:
            action.setStatusTip(status_tip)
        if whats_this:
            action.setWhatsThis(whats_this)
        if add_to_toolbar:
            self.toolbar.addAction(action)
        if add_to_menu:
            self.iface.addPluginToVectorMenu(self.menu, action)
        self.actions.append(action)
        return action


    def initGui(self):
        """Create menu entries and toolbar icons."""
        # The icon is loaded from a file rather than through a Qt resource: the
        # compiled resources.py was never imported anywhere, so ':/plugins/...'
        # resolved to an empty QIcon and the toolbar button came out blank
        icon_path = os.path.join(self.plugin_dir, 'icon.png')
        self.add_action(
            icon_path,
            text=self.tr(u'Spectral characteristics and typicality'),
            callback=self.run,
            parent=self.iface.mainWindow())

        # Collect masks left over from previous sessions (a QGIS crash, say)
        try:
            stale = cleanup_stale_masks()
            if stale:
                print(f"Stale mask files removed: {stale}")
        except Exception:
            pass

